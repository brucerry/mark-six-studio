#!/usr/bin/env python3
"""Write the bounded native-cleanup inventory before the final bundle seal.

The root macOS executable and CodeResources are generated by that seal; the
native executor must verify them through Security.framework instead of hashing
them through a self-referential resource manifest.
"""
import argparse
import hashlib
import os
from pathlib import Path, PurePosixPath
from urllib.parse import quote


def write_payload(root: Path, macos: bool) -> Path:
    root = root.resolve(strict=True)
    destination = root / ("Contents/Resources/maintenance-payload.txt" if macos else "maintenance-payload.txt")
    excluded = {destination.relative_to(root).as_posix()}
    if macos:
        excluded.update({"Contents/MacOS/mark-six-studio", "Contents/_CodeSignature/CodeResources"})
    else:
        excluded.add("manifest.json")  # Validated as typed metadata by the native reader.
    entries = []
    for directory, names, files in os.walk(root, followlinks=False):
        for name in sorted(names + files):
            path = Path(directory) / name
            relative = path.relative_to(root).as_posix()
            if relative in excluded:
                continue
            if path.is_symlink():
                target = path.readlink().as_posix()
                if PurePosixPath(target).is_absolute():
                    raise ValueError("Absolute payload link: " + relative)
                resolved = path.resolve(strict=True)
                if root not in resolved.parents:
                    raise ValueError("Escaping payload link: " + relative)
                kind, evidence = "L", quote(target, safe="/-._~")
            elif path.is_dir():
                kind, evidence = "D", "-"
            elif path.is_file():
                if path.suffix.lower() in {".msx", ".sqlite", ".sqlite3", ".db", ".pfx", ".p12"}:
                    raise ValueError("User data or credentials in payload: " + relative)
                digest = hashlib.sha256()
                with path.open("rb") as source:
                    for chunk in iter(lambda: source.read(65536), b""):
                        digest.update(chunk)
                kind, evidence = "F", digest.hexdigest()
            else:
                raise ValueError("Unsupported payload member: " + relative)
            entries.append(f"{kind}\t{evidence}\t{quote(relative, safe='/-._~')}\n")
            if len(entries) > 100000:
                raise ValueError("Payload entry limit exceeded")
    payload = "M6PAYLOAD\t1\tcom.brucerry.marksixstudio\n" + "".join(sorted(entries))
    if len(payload.encode("utf-8")) > 8 * 1024 * 1024:
        raise ValueError("Payload manifest size limit exceeded")
    destination.parent.mkdir(parents=True, exist_ok=True)
    destination.write_bytes(payload.encode("utf-8"))
    return destination


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("root", type=Path)
    parser.add_argument("--macos", action="store_true")
    arguments = parser.parse_args()
    write_payload(arguments.root, arguments.macos)
